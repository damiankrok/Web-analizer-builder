export const GLYPH_W = 5
export const GLYPH_H = 7
export const textWidth = (s: string, scale: number): number => s.length * (GLYPH_W + 1) * scale

export type Painter = (x: number, y: number, r: number, g: number, b: number) => void

/** Draw a string with its top-left corner at (x, y). */
export function drawText(
  put: Painter,
  s: string,
  x: number,
  y: number,
  scale: number,
  colour: [number, number, number],
): void {
  let cx = x
  for (const raw of s.toUpperCase()) {
    const rows = F[raw] ?? F['?']
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (rows[r][c] !== '1') continue
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) put(cx + c * scale + dx, y + r * scale + dy, ...colour)
        }
      }
    }
    cx += (GLYPH_W + 1) * scale
  }
}
